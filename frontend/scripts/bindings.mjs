// Writes the frontend's two modules over the bindings `wails3 generate bindings` makes in
// frontend/bindings (make bindings runs both, #854):
//
// - src/lib/wails/App.ts: one function a bound method, calling it through window.go.main.App at call
//   time, as v2's wailsjs/go/main/App.js did. The probes swap a method there for a stand-in
//   (compile-spawns.js), and the page's own calls must reach the stand-in, which a direct import of
//   the generated functions would not.
// - src/lib/wails/models.ts: the Go structs as one namespace a package (vmangos.Area, main.PrefabFile),
//   as v2's wailsjs/go/models.ts had them.
//
// With --check it writes nothing and fails when either file is out of step with frontend/bindings.
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs'
import { join, dirname, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const frontend = join(dirname(fileURLToPath(import.meta.url)), '..')
const bindings = join(frontend, 'bindings', 'Meld')
const out = join(frontend, 'src', 'lib', 'wails')
const check = process.argv.includes('--check')

const header = '// Generated by frontend/scripts/bindings.mjs from frontend/bindings (make bindings). Do not edit.\n'

const appSrc = readFileSync(join(bindings, 'app.ts'), 'utf8')
const methods = [...appSrc.matchAll(/^export function ([A-Z][A-Za-z0-9]*)\(.*\): \$CancellablePromise<(.*)> \{$/gm)]
const names = methods.map((m) => m[1]).sort()
// Every bound method that returns a Go pointer returns an error with it, so a call that succeeds never
// gives null: these are typed without it, as v2 typed them.
const nonNull = new Set(methods.filter((m) => m[2].endsWith(' | null')).map((m) => m[1]))
if (names.length !== [...appSrc.matchAll(/^export function /gm)].length) throw new Error('bindings: an export of frontend/bindings/Meld/app.ts did not parse')

let app = header
app += `
import * as Bound from '../../../bindings/Meld/app'

/** The bound methods of Go's App, as the page calls them. */
export type AppApi = typeof Bound

type GoGlobal = { go?: { main: { App: AppApi } } }

// One table the calls go through, on window.go.main.App, so a probe can swap a method for a stand-in.
// It is there only when Go serves the page (/meld/backend.js, main.go), so hasBackend() tells a page
// without the Go side, such as a plain \`bun run dev\`.
const g = globalThis as GoGlobal & { __meldBackend?: boolean }
if (g.__meldBackend) g.go = { main: { App: { ...Bound } } }
const api = (): AppApi => (g.go as { main: { App: AppApi } }).main.App
type NonNullCall<F extends (...a: never[]) => PromiseLike<unknown>> = (...a: Parameters<F>) => Promise<NonNullable<Awaited<ReturnType<F>>>>
`
for (const n of names) {
	if (nonNull.has(n)) app += `\nexport const ${n}: NonNullCall<AppApi['${n}']> = (...a) => api().${n}(...a) as Promise<NonNullable<Awaited<ReturnType<AppApi['${n}']>>>>`
	else app += `\nexport const ${n}: AppApi['${n}'] = (...a) => api().${n}(...a)`
}
app += '\n'

const packages = [['main', join(bindings, 'models.ts')]]
const internal = join(bindings, 'internal')
for (const p of readdirSync(internal).sort()) {
	const f = join(internal, p, 'models.ts')
	if (existsSync(f)) packages.push([p, f])
}
let models = header + '\n'
for (const [ns, f] of packages) {
	const spec = relative(out, f).replaceAll('\\', '/').replace(/\.ts$/, '')
	models += `export * as ${ns} from '${spec}'\n`
}

const files = [
	[join(out, 'App.ts'), app],
	[join(out, 'models.ts'), models],
]
let stale = false
for (const [f, text] of files) {
	const now = existsSync(f) ? readFileSync(f, 'utf8') : ''
	if (now === text) continue
	if (check) {
		console.error(`${relative(frontend, f)} is out of step with frontend/bindings: run make bindings`)
		stale = true
	} else writeFileSync(f, text)
}
if (stale) process.exit(1)
if (!check) console.log(`bindings: ${names.length} methods, ${packages.length} model packages`)
