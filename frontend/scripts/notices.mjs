// Writes the generated half of ../THIRD_PARTY_NOTICES.md: every library the shipped app bundles
// (the npm runtime closure of frontend/package.json "dependencies", and the Go modules in the
// binary's build graph for Windows and Linux) with its licence and the licence file's text.
//
//   bun scripts/notices.mjs            rewrite THIRD_PARTY_NOTICES.md (make notices)
//   bun scripts/notices.mjs --check    fail on a licence outside the allow list, or when the file is
//                                      out of date (part of make check)
//
// Needs node_modules (bun install) and the Go module cache. Licence names of Go modules are
// recognised from their licence text, since Go modules carry no licence field.

import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const frontend = resolve(here, '..')
const root = resolve(frontend, '..')
const outFile = join(root, 'THIRD_PARTY_NOTICES.md')
const MARK = '<!-- Everything below is generated by `make notices`; edit scripts/notices.mjs, not this part. -->'

// Licences that may ship in the app (permissive only, CLAUDE.md "Reuse existing code").
const SHIPPED = new Set(['MIT', 'ISC', 'BSD-2-Clause', 'BSD-3-Clause', 'Apache-2.0', 'Zlib', '0BSD', 'Unlicense'])
// Build-time tools may also be MPL-2.0 (lightningcss, vite's CSS minifier): not shipped, not modified.
const BUILD_TIME = new Set([...SHIPPED, 'MPL-2.0', 'CC0-1.0', 'BlueOak-1.0.0', 'Python-2.0', 'CC-BY-4.0', '(MIT OR CC0-1.0)'])

const failures = []

function normalizeSpdx(s) {
	if (!s) return ''
	if (s.toLowerCase() === 'zlib') return 'Zlib'
	return s
}

function licenceFile(dir) {
	if (!existsSync(dir)) return null
	const names = readdirSync(dir).filter((f) => /^(licen[cs]e|copying|notice)(\.|$|-)/i.test(f))
	names.sort((a, b) => rank(a) - rank(b))
	return names.length ? join(dir, names[0]) : null
}
function rank(n) {
	return /^licen[cs]e/i.test(n) ? 0 : /^copying/i.test(n) ? 1 : 2
}

function readText(p) {
	return readFileSync(p, 'utf8').replace(/\r\n/g, '\n').trim()
}

function detect(text) {
	if (/Apache License/i.test(text) && /Version 2\.0/.test(text)) return 'Apache-2.0'
	if (/Mozilla Public License/i.test(text)) return 'MPL-2.0'
	if (/GNU (Affero |Lesser |Library )?General Public License/i.test(text)) return 'GPL-family'
	if (/Permission is hereby granted, free of charge/i.test(text)) return 'MIT'
	if (/Redistribution and use in source and binary forms/i.test(text)) {
		return /Neither the name/i.test(text) ? 'BSD-3-Clause' : 'BSD-2-Clause'
	}
	if (/Permission to use, copy, modify, and\/or distribute/i.test(text)) return 'ISC'
	if (/altered source versions must be plainly marked/i.test(text)) return 'Zlib'
	return 'UNKNOWN'
}

// ---- npm: the runtime closure -------------------------------------------------------------

const pkg = JSON.parse(readFileSync(join(frontend, 'package.json'), 'utf8'))
const nm = join(frontend, 'node_modules')

function findPackage(name, fromDir) {
	// Node resolution: nearest node_modules up from the requiring package, then the root's.
	let dir = fromDir
	while (true) {
		const p = join(dir, 'node_modules', name)
		if (existsSync(join(p, 'package.json'))) return p
		const up = dirname(dir)
		if (up === dir || up.length < frontend.length) break
		dir = up
	}
	const p = join(nm, name)
	return existsSync(join(p, 'package.json')) ? p : null
}

function npmLicence(j) {
	if (typeof j.license === 'string') return j.license
	if (j.license && j.license.type) return j.license.type
	if (Array.isArray(j.licenses)) return j.licenses.map((l) => l.type).join(' OR ')
	return ''
}

const npm = new Map()
function walk(name, fromDir) {
	const dir = findPackage(name, fromDir)
	if (!dir) {
		failures.push(`npm: ${name} is not installed (run bun install in frontend)`)
		return
	}
	const j = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
	const key = `${j.name}@${j.version}`
	if (npm.has(key)) return
	npm.set(key, { name: j.name, version: j.version, dir, licence: normalizeSpdx(npmLicence(j)) })
	for (const dep of Object.keys(j.dependencies ?? {})) walk(dep, dir)
}
for (const dep of Object.keys(pkg.dependencies ?? {})) walk(dep, frontend)

// ---- npm: everything installed, for the allow list ----------------------------------------

function installed() {
	const out = []
	for (const e of readdirSync(nm, { withFileTypes: true })) {
		if (e.name.startsWith('.')) continue
		const dirs = e.name.startsWith('@') ? readdirSync(join(nm, e.name)).map((n) => join(nm, e.name, n)) : [join(nm, e.name)]
		for (const d of dirs) {
			if (!existsSync(join(d, 'package.json'))) continue
			const j = JSON.parse(readFileSync(join(d, 'package.json'), 'utf8'))
			out.push({ name: j.name, version: j.version, licence: normalizeSpdx(npmLicence(j)) })
		}
	}
	return out
}

// ---- Go: the modules in the build graph ---------------------------------------------------

function goModules() {
	const mods = new Map()
	for (const [goos, cgo] of [
		['windows', '0'],
		['linux', '1'],
	]) {
		const out = execFileSync('go', ['list', '-deps', '-e', '-tags', 'desktop,production,webkit2_41', '-f', '{{with .Module}}{{if not .Main}}{{.Path}}|{{.Version}}|{{.Dir}}{{end}}{{end}}', '.'], {
			cwd: root,
			encoding: 'utf8',
			env: { ...process.env, GOOS: goos, CGO_ENABLED: cgo },
			maxBuffer: 1 << 26,
		})
		for (const line of out.split('\n')) {
			if (!line.trim()) continue
			const [path, version, dir] = line.trim().split('|')
			mods.set(path, { name: path, version, dir })
		}
	}
	return [...mods.values()].sort((a, b) => a.name.localeCompare(b.name))
}

// ---- build the report ---------------------------------------------------------------------

const entries = []
for (const p of [...npm.values()].sort((a, b) => a.name.localeCompare(b.name))) {
	const f = licenceFile(p.dir)
	const text = f ? readText(f) : ''
	let lic = p.licence || (text ? detect(text) : '')
	entries.push({ kind: 'npm', name: p.name, version: p.version, licence: lic, text })
}
for (const m of goModules()) {
	const f = licenceFile(m.dir)
	const text = f ? readText(f) : ''
	entries.push({ kind: 'go', name: m.name, version: m.version, licence: text ? detect(text) : '', text })
}

for (const e of entries) {
	if (!SHIPPED.has(e.licence)) failures.push(`${e.kind}: ${e.name}@${e.version} ships under "${e.licence || 'no licence found'}", which is not in the allow list`)
	if (!e.text) failures.push(`${e.kind}: ${e.name}@${e.version} has no licence file to include`)
}
for (const i of installed()) {
	if (!BUILD_TIME.has(i.licence)) failures.push(`npm (build time): ${i.name}@${i.version} is "${i.licence || 'unlicensed'}", which is not in the allow list`)
}

function section(kind, title, intro) {
	const list = entries.filter((e) => e.kind === kind)
	let s = `## ${title}\n\n${intro}\n\n| Package | Version | Licence |\n|---|---|---|\n`
	for (const e of list) s += `| ${e.name} | ${e.version} | ${e.licence} |\n`
	s += '\n'
	for (const e of list) s += `### ${e.name} ${e.version}\n\n\`\`\`\n${e.text}\n\`\`\`\n\n`
	return s
}

const generated =
	`${MARK}\n\n` +
	section('npm', 'Bundled npm packages', "Compiled into the app's frontend bundle (`frontend/dist`, embedded in the binary): the runtime dependencies of `frontend/package.json` and theirs.") +
	section('go', 'Linked Go modules', 'Linked into the Windows and Linux binaries (`go list -deps`, the `desktop,production,webkit2_41` build tags).') +
	'## Build-time tools\n\nThe frontend build uses tools that are not shipped, among them `lightningcss` (MPL-2.0, pulled in by Vite as its CSS minifier). They are used unmodified and none of their code is in the app.\n'

const current = existsSync(outFile) ? readFileSync(outFile, 'utf8').replace(/\r\n/g, '\n') : ''
const at = current.indexOf(MARK)
const head = at >= 0 ? current.slice(0, at) : current.replace(/\s*$/, '\n\n')
const next = head + generated

if (process.argv.includes('--check')) {
	if (at < 0 || current !== next) failures.push('THIRD_PARTY_NOTICES.md is out of date: run make notices')
	if (failures.length) {
		console.error('notices check failed:\n  ' + failures.join('\n  '))
		process.exit(1)
	}
	console.log(`notices: ${entries.length} shipped libraries, all permissive, file up to date`)
} else {
	if (failures.length) {
		console.error('notices:\n  ' + failures.join('\n  '))
		process.exit(1)
	}
	writeFileSync(outFile, next)
	console.log(`wrote ${outFile} (${entries.length} libraries)`)
}
